class Solution {
public:
    int minMoves(vector<int>& nums, int limit) {
        int n = nums.size();
        // 差分数组，大小设为 2*limit + 2 以防越界
        vector<int> diff(2 * limit + 2, 0);

        for (int i = 0; i < n / 2; ++i) {
            int a = nums[i];
            int b = nums[n - 1 - i];
            if (a > b) swap(a, b); // 保证 a <= b

            // 默认全区间 [2, 2*limit] 都需要 2 次操作
            // 根据差分思想：
            // [2, a] 需要 2 次
            // [a + 1, b + limit] 需要 1 次
            // [b + limit + 1, 2 * limit] 需要 2 次
            // 特殊点 a + b 需要 0 次

            // 1. 全局默认 +2
            diff[2] += 2;
            diff[2 * limit + 1] -= 2;

            // 2. [a + 1, b + limit] 区间修改：2次 -> 1次，即 -1
            diff[a + 1] -= 1;
            diff[b + limit + 1] += 1;

            // 3. 特殊点 a + b 修改：1次 -> 0次，即 -1
            diff[a + b] -= 1;
            diff[a + b + 1] += 1;
        }

        int ans = n; // 最大操作次数不会超过 n
        int current_moves = 0;
        // 遍历所有可能的和 S，从 2 到 2*limit
        for (int s = 2; s <= 2 * limit; ++s) {
            current_moves += diff[s];
            ans = min(ans, current_moves);
        }

        return ans;
    }
};//////////////////////////////////////////////////////////////////////////////////////////////////
